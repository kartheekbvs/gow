#!/usr/bin/env python3
"""Assemble a PyDocs Dojo track data file from notebook fragments.

Usage:
    python3 scripts/build_track.py <meta.json> <parts_dir> <output.js> [--verify]

  meta.json    track metadata: id, title, icon, tagline, accent, engine,
               packages
  parts_dir    directory of *.json files, one notebook object per file
               (notebooks are sorted by their "order" field)
  output.js    the assembled data file consumed by the notebook editor
  --verify     run scripts/verify_practice.py on the result afterwards

Edit fragments in practice/parts/<track>/, then rebuild. Never hand-edit the
generated .js file.
"""
import glob
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    if len(sys.argv) < 4:
        print(__doc__)
        return 2
    meta_path, parts_dir, out_path = sys.argv[1:4]
    verify = "--verify" in sys.argv

    with open(meta_path, encoding="utf-8") as f:
        meta = json.load(f)
    for k in ("id", "title", "icon", "tagline", "accent", "engine"):
        if k not in meta:
            print("meta missing field '%s'" % k)
            return 2
    meta.setdefault("packages", [])

    frags = sorted(glob.glob(os.path.join(parts_dir, "*.json")))
    if not frags:
        print("no fragments found in %s" % parts_dir)
        return 2
    notebooks = []
    ids = set()
    for fp in frags:
        with open(fp, encoding="utf-8") as f:
            nb = json.load(f)
        if nb.get("id") in ids:
            print("DUPLICATE notebook id in %s: %s" % (fp, nb.get("id")))
            return 2
        ids.add(nb.get("id"))
        notebooks.append(nb)
    notebooks.sort(key=lambda n: n.get("order", 9999))

    track = dict(meta)
    track["notebooks"] = notebooks
    payload = json.dumps(track, indent=2, ensure_ascii=False)

    rel_parts = os.path.relpath(parts_dir, ROOT)
    js = ("/* PyDocs Dojo — track data: %s\n"
          "   GENERATED by scripts/build_track.py from %s — edit the\n"
          "   fragments and rebuild; do not hand-edit this file. */\n\n"
          "window.PRACTICE_TRACKS.push(\n%s\n);\n"
          % (meta["id"], rel_parts, payload))
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(js)
    n_ex = sum(len([c for c in nb["cells"] if c.get("type") == "exercise"])
               for nb in notebooks)
    print("wrote %s : %d notebooks, %d exercises"
          % (os.path.relpath(out_path, ROOT), len(notebooks), n_ex))

    if verify:
        r = subprocess.run([sys.executable,
                            os.path.join(ROOT, "scripts", "verify_practice.py"),
                            os.path.abspath(out_path)], cwd=ROOT)
        return r.returncode
    return 0


if __name__ == "__main__":
    sys.exit(main())
